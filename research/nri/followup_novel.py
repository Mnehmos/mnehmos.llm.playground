"""POST-HOC follow-up to docs/17 (not part of the docs/16 registration).

The docs/16-17 evaluation sample was a fresh random DRAW, but the task has only 7,350 distinct
in-distribution questions, so most scored rows repeat a question already seen while fitting
the editors or in the development sample. This script re-scores every editor, unchanged, on
the questions the editors had NOT seen, each distinct question counted once:

  not_fit      eligible test questions absent from the editor-fitting sample (FIT_S)
  not_fit_dev  ... and also absent from the development sample (DEV_S)

Only the subset changes. The networks, locations, editors, fitting data and scorer are all
identical to run_editors.py. All networks were trained on the full question set, so "unseen"
means unseen by the editor, not by the network.

    python followup_novel.py && python followup_novel.py --report
"""
from __future__ import annotations

import argparse
import json
import statistics as st
from concurrent.futures import ProcessPoolExecutor

import run_editors as E
import run_swap as S

KEYS = ("m", "mu", "a", "au", "fu", "order")
_score = S.score


def keys(lat):
    return list(zip(*[lat[k].tolist() for k in KEYS]))


def subset_mask(lat, which):
    seen = set(keys(S.lats(8192, S.FIT_S)))
    if which == "not_fit_dev":
        seen |= set(keys(S.lats(E.N_EVAL, E.DEV_S)))
    ok = S.eligible(lat, E.KIND).tolist()
    first, mask = set(), []
    for k, e in zip(keys(lat), ok):
        keep = e and k not in seen and k not in first
        first.add(k)
        mask.append(keep)
    return mask


def run(args):
    path, which = args
    cache = {}

    def score_subset(pred, lat, var, kind):
        if id(lat) not in cache:
            import torch
            cache[id(lat)] = torch.tensor(subset_mask(lat, which))
        mk = cache[id(lat)]
        return _score(pred[mk], {k: v[mk] for k, v in lat.items()}, var, kind)

    S.score = score_subset
    try:
        return E.analyse((path, "test"))
    finally:
        S.score = _score


def report():
    res = json.loads((E.OUT / "followup_novel.json").read_text())
    space = E.TABLE_SPACE
    PAIRS = [("1 weight edit", "w_pooled", "w_route"),
             ("2 stored table", f"t_pooled_{space}", f"t_route_{space}"),
             ("3 per-question", "q_pooled", "q_route_uo")]
    POP = [("mass declared", "mass_only", "M"), ("acceleration declared", "acc_only", "A")]
    L = ["# POST-HOC follow-up: questions the editors had not seen (auto-generated by `followup_novel.py --report`)", "",
         "Not part of the docs/16 registration. Same networks, locations, editors, fitting data and scorer;",
         "only the scored subset changes, and each distinct question counts once.", ""]
    for which, title in (("not_fit_dev", "Not in the editor-fitting OR development samples"),
                         ("not_fit", "Not in the editor-fitting sample")):
        R = {(r["group"], r["seed"]): r for r in res[which]}
        get = lambda g, s, v, e, k: R[(g, s)][f"{v}_das"][e][k]
        n = get("mass_only", 300, "M", "copy", "n_eligible")
        L += [f"## {title}: {n} distinct eligible questions per network (DAS location, all 12 seeds)", "",
              "| editor | tier | mass declared: intended | wrong | acceleration declared: intended | wrong |",
              "|---|---|---|---|---|---|"]
        for name, tier, e in (("current (doc 15)", "1", "w_current"), ("pooled, wide input", "1", "w_pooled"),
                              ("route-aware, wide input", "1", "w_route"), ("pooled table", "2", f"t_pooled_{space}"),
                              ("route-aware table", "2", f"t_route_{space}"), ("pooled, per-question", "3", "q_pooled"),
                              ("route-aware, per-question", "3", "q_route_uo"), ("copy (benchmark)", "3", "copy")):
            f = lambda g, v, k: st.mean(get(g, s, v, e, k) for s in E.SEEDS)
            L.append(f"| {name} | {tier} | {f('mass_only', 'M', 'intended'):.3f} | {f('mass_only', 'M', 'wrong'):.3f} | "
                     f"{f('acc_only', 'A', 'intended'):.3f} | {f('acc_only', 'A', 'wrong'):.3f} |")
        L += ["", "Route-aware − pooled, paired by network (exploratory; no correction):", "",
              "| tier | population | Δ intended | 95% CI | p | networks > 0 | Δ wrong | p |", "|---|---|---|---|---|---|---|---|"]
        for tier, a, b in PAIRS:
            for pname, g, v in POP:
                d = [get(g, s, v, b, "intended") - get(g, s, v, a, "intended") for s in E.SEEDS]
                w = [get(g, s, v, b, "wrong") - get(g, s, v, a, "wrong") for s in E.SEEDS]
                lo, hi = S.boot_ci(d)
                L.append(f"| {tier} | {pname} | {st.mean(d):+.3f} | [{lo:+.3f}, {hi:+.3f}] | {S.paired_signflip(d):.4f} | "
                         f"{sum(x > 0 for x in d)}/12 | {st.mean(w):+.3f} | {S.paired_signflip(w):.3f} |")
        L.append("")
    (E.OUT / "followup_novel.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args()
    if a.report:
        report()
        return
    out = {}
    for which in ("not_fit_dev", "not_fit"):
        jobs = [(str(E.ZOO / f"{g}_s{s}"), which) for s in E.SEEDS for g in E.GROUPS]
        with ProcessPoolExecutor(4) as ex:
            out[which] = list(ex.map(run, jobs))
    (E.OUT / "followup_novel.json").write_text(json.dumps(out, indent=1))
    report()


if __name__ == "__main__":
    main()
